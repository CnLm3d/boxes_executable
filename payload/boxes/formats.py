import io
import os
import re
import shutil
import subprocess
import tempfile
from boxes.drawing import Context, LBRN2Surface, PSSurface, SVGSurface
from boxes.stl_exporter import STLSurface


def _cubic_bezier_pts(x0, y0, x1, y1, x2, y2, x3, y3, steps=12):
    pts = []
    for s in range(1, steps + 1):
        t = s / float(steps)
        mt = 1.0 - t
        px = (mt**3) * x0 + 3 * (mt**2) * t * x1 + 3 * mt * (t**2) * x2 + (t**3) * x3
        py = (mt**3) * y0 + 3 * (mt**2) * t * y1 + 3 * mt * (t**2) * y2 + (t**3) * y3
        pts.append((px, py))
    return pts


def _parse_ps_strokes(ps_text: str):
    """Parse PSSurface output into a list of (rgb, lw, polylines) in mm."""
    pt_to_mm = 25.4 / 72.0
    strokes = []
    in_path = False
    cur_polylines = []
    cur_poly = []
    cur_rgb = (0.0, 0.0, 0.0)
    cur_lw = 0.2
    cx, cy = 0.0, 0.0

    bbox = (210.0, 297.0)
    m_bb = re.search(r"%%BoundingBox:\s+0\s+0\s+(\d+)\s+(\d+)", ps_text)
    if m_bb:
        bbox = (float(m_bb.group(1)) * pt_to_mm, float(m_bb.group(2)) * pt_to_mm)

    for raw in ps_text.splitlines():
        line = raw.strip()
        if not line or line.startswith("%"):
            continue
        if line == "newpath":
            in_path = True
            cur_polylines = []
            cur_poly = []
            continue
        if not in_path:
            continue
        if line == "stroke":
            if len(cur_poly) >= 2:
                cur_polylines.append(cur_poly)
            if cur_polylines:
                strokes.append((cur_rgb, cur_lw, cur_polylines))
            in_path = False
            continue

        parts = line.split()
        cmd = parts[-1]
        if cmd == "moveto" and len(parts) == 3:
            if len(cur_poly) >= 2:
                cur_polylines.append(cur_poly)
            cx = float(parts[0]) * pt_to_mm
            cy = float(parts[1]) * pt_to_mm
            cur_poly = [(cx, cy)]
        elif cmd == "lineto" and len(parts) == 3:
            cx = float(parts[0]) * pt_to_mm
            cy = float(parts[1]) * pt_to_mm
            cur_poly.append((cx, cy))
        elif cmd == "curveto" and len(parts) == 7:
            x1, y1, x2, y2, x3, y3 = [float(v) * pt_to_mm for v in parts[:6]]
            for px, py in _cubic_bezier_pts(cx, cy, x1, y1, x2, y2, x3, y3):
                cur_poly.append((px, py))
            cx, cy = x3, y3
        elif cmd == "setlinewidth" and len(parts) == 2:
            cur_lw = float(parts[0]) * pt_to_mm
        elif cmd == "setrgbcolor" and len(parts) == 4:
            cur_rgb = (float(parts[0]), float(parts[1]), float(parts[2]))

    return bbox, strokes


def _ps_to_dxf(ps_bytes: bytes) -> bytes:
    ps_text = ps_bytes.decode("utf-8", errors="replace")
    _, strokes = _parse_ps_strokes(ps_text)
    out = [
        "0", "SECTION",
        "2", "HEADER",
        "9", "$INSUNITS",
        "70", "4",  # 4 = Millimeters
        "0", "ENDSEC",
        "0", "SECTION",
        "2", "ENTITIES"
    ]
    for rgb, _, polylines in strokes:
        # Map RGB to AutoCAD ACI color (1=Red, 3=Green, 5=Blue, 7=White/Black)
        r, g, b = rgb
        aci = 7
        if r > 0.5 and g < 0.3 and b < 0.3:
            aci = 1
        elif b > 0.5 and r < 0.3:
            aci = 5
        elif g > 0.5 and r < 0.3:
            aci = 3

        for poly in polylines:
            for i in range(len(poly) - 1):
                x0, y0 = poly[i]
                x1, y1 = poly[i + 1]
                out.extend([
                    "0", "LINE",
                    "8", "0",
                    "62", str(aci),
                    "10", f"{x0:.4f}",
                    "20", f"{y0:.4f}",
                    "30", "0.0",
                    "11", f"{x1:.4f}",
                    "21", f"{y1:.4f}",
                    "31", "0.0"
                ])
    out.extend(["0", "ENDSEC", "0", "EOF", ""])
    return "\r\n".join(out).encode("utf-8")


def _ps_to_gcode(ps_bytes: bytes) -> bytes:
    ps_text = ps_bytes.decode("utf-8", errors="replace")
    _, strokes = _parse_ps_strokes(ps_text)
    out = [
        "; Generated by Boxes.py Desktop Studio",
        "G21 ; Millimeters",
        "G90 ; Absolute positioning",
        "M5  ; Laser off"
    ]
    for _, _, polylines in strokes:
        for poly in polylines:
            if not poly:
                continue
            x0, y0 = poly[0]
            out.append(f"G0 X{x0:.3f} Y{y0:.3f}")
            out.append("M3 S1000")
            for x, y in poly[1:]:
                out.append(f"G1 X{x:.3f} Y{y:.3f} F1200")
            out.append("M5")
    out.append("G0 X0 Y0")
    out.append("M2")
    return "\n".join(out).encode("utf-8")


def _ps_to_plt(ps_bytes: bytes) -> bytes:
    ps_text = ps_bytes.decode("utf-8", errors="replace")
    _, strokes = _parse_ps_strokes(ps_text)
    # 1 mm = 40 HPGL plotter units
    scale = 40.0
    out = ["IN;", "SP1;"]
    for _, _, polylines in strokes:
        for poly in polylines:
            if not poly:
                continue
            x0, y0 = poly[0]
            out.append(f"PU{int(round(x0*scale))},{int(round(y0*scale))};")
            coords = ",".join(f"{int(round(x*scale))},{int(round(y*scale))}" for x, y in poly[1:])
            if coords:
                out.append(f"PD{coords};")
    out.append("PU0,0;SP0;")
    return "\n".join(out).encode("utf-8")


def _ps_to_pdf(ps_bytes: bytes) -> bytes:
    """Pure-Python vector PDF 1.4 generator directly from PostScript strokes."""
    ps_text = ps_bytes.decode("utf-8", errors="replace")
    (w_mm, h_mm), strokes = _parse_ps_strokes(ps_text)
    mm_to_pt = 72.0 / 25.4
    w_pt = max(10.0, w_mm * mm_to_pt)
    h_pt = max(10.0, h_mm * mm_to_pt)

    stream_lines = ["1 J 1 j"]
    for (r, g, b), lw_mm, polylines in strokes:
        lw_pt = max(0.2, lw_mm * mm_to_pt)
        stream_lines.append(f"{lw_pt:.3f} w {r:.2f} {g:.2f} {b:.2f} RG")
        for poly in polylines:
            if not poly:
                continue
            x0, y0 = poly[0]
            stream_lines.append(f"{x0*mm_to_pt:.3f} {y0*mm_to_pt:.3f} m")
            for x, y in poly[1:]:
                stream_lines.append(f"{x*mm_to_pt:.3f} {y*mm_to_pt:.3f} l")
            stream_lines.append("S")

    content_bytes = "\n".join(stream_lines).encode("latin-1")

    objs = []
    objs.append(b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n")
    objs.append(b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n")
    objs.append(
        f"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {w_pt:.2f} {h_pt:.2f}] /Contents 4 0 R >>\nendobj\n".encode("latin-1")
    )
    objs.append(
        f"4 0 obj\n<< /Length {len(content_bytes)} >>\nstream\n".encode("latin-1")
        + content_bytes
        + b"\nendstream\nendobj\n"
    )

    pdf = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for obj in objs:
        offsets.append(len(pdf))
        pdf.extend(obj)

    xref_pos = len(pdf)
    pdf.extend(f"xref\n0 {len(offsets)}\n0000000000 65535 f \n".encode("latin-1"))
    for off in offsets[1:]:
        pdf.extend(f"{off:010d} 00000 n \n".encode("latin-1"))
    pdf.extend(
        f"trailer\n<< /Size {len(offsets)} /Root 1 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n".encode("latin-1")
    )
    return bytes(pdf)


class Formats:

    pstoedit_candidates = ["/usr/bin/pstoedit", "pstoedit", r"C:\Program Files\pstoedit\pstoedit.exe", "pstoedit.exe"]
    ps2pdf_candidates = ["/usr/bin/ps2pdf", "ps2pdf", "ps2pdf.exe"]

    _BASE_FORMATS = ['svg', 'svg_Ponoko', 'ps', 'lbrn2', 'stl']

    formats = {
        "svg": None,
        "svg_Ponoko": None,
        "ps": None,
        "lbrn2": None,
        "stl": None,
        "dxf": "{pstoedit} -flat 0.1 -f dxf:-mm {input} {output}",
        "gcode": "{pstoedit} -f gcode {input} {output}",
        "plt": "{pstoedit} -f hpgl {input} {output}",
        "pdf": "{ps2pdf} -dEPSCrop {input} {output}",
    }

    http_headers = {
        "svg": [('Content-type', 'image/svg+xml; charset=utf-8')],
        "svg_Ponoko": [('Content-type', 'image/svg+xml; charset=utf-8')],
        "ps": [('Content-type', 'application/postscript')],
        "lbrn2": [('Content-type', 'application/lbrn2')],
        "stl": [('Content-type', 'application/zip')],
        "dxf": [('Content-type', 'image/vnd.dxf')],
        "plt": [('Content-type', 'application/vnd.hp-hpgl')],
        "gcode": [('Content-type', 'text/plain; charset=utf-8')],
        "pdf": [('Content-type', 'application/pdf')],
    }

    def __init__(self) -> None:
        self.pstoedit = None
        self.ps2pdf = None
        for cmd in self.pstoedit_candidates:
            self.pstoedit = shutil.which(cmd)
            if self.pstoedit:
                break
        for cmd in self.ps2pdf_candidates:
            self.ps2pdf = shutil.which(cmd)
            if self.ps2pdf:
                break

    def getFormats(self):
        return sorted(self.formats.keys())

    def getSurface(self, fmt):
        if fmt in ("svg", "svg_Ponoko"):
            surface = SVGSurface()
        elif fmt == "lbrn2":
            surface = LBRN2Surface()
        elif fmt == "stl":
            surface = STLSurface()
        else:
            surface = PSSurface()

        ctx = Context(surface)
        return surface, ctx

    def convert(self, data, fmt):
        if fmt not in self._BASE_FORMATS:
            raw_ps = data.getvalue()
            if fmt == "dxf" and not self.pstoedit:
                return io.BytesIO(_ps_to_dxf(raw_ps))
            if fmt == "gcode" and not self.pstoedit:
                return io.BytesIO(_ps_to_gcode(raw_ps))
            if fmt == "plt" and not self.pstoedit:
                return io.BytesIO(_ps_to_plt(raw_ps))
            if fmt == "pdf" and not self.ps2pdf:
                return io.BytesIO(_ps_to_pdf(raw_ps))

            fd, tmpfile = tempfile.mkstemp()
            try:
                os.write(fd, raw_ps)
                os.close(fd)
                fd2, outfile = tempfile.mkstemp()
                try:
                    cmd = self.formats[fmt].format(
                        pstoedit=self.pstoedit,
                        ps2pdf=self.ps2pdf,
                        input=tmpfile,
                        output=outfile).split()
                    result = subprocess.run(cmd)
                    if result.returncode:
                        raise ValueError(f"Conversion failed. pstoedit returned {result.returncode}\n\n {result.stderr}")
                    with open(outfile, 'rb') as ff:
                        data = io.BytesIO(ff.read())
                finally:
                    os.close(fd2)
                    os.unlink(outfile)
            finally:
                os.unlink(tmpfile)

        return data
